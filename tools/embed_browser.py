#!/usr/bin/env python3
"""Embed local browser assets, so existing on-device packages need no web root."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
result = ['/* Generated by tools/embed_browser.py; SPDX-License-Identifier: GPL-3.0-or-later */', '#pragma once', '#include <string.h>', '#include <stdbool.h>']
assets = []
for filename in ['index.html','player.js','protocol.js','renderers.js','video-worker.js','probe.html','probe.js']:
    path = root / 'web' / filename
    name = {'index.html':'browser_index_html','player.js':'browser_player_js','probe.html':'browser_probe_html','probe.js':'browser_probe_js'}.get(filename, 'browser_'+filename.replace('/','_').replace('.','_'))
    if filename.endswith('.wasm'):
        data = path.read_bytes()
        result.append(f'static const unsigned char {name}[] = {{')
        result.extend(','.join('0x%02x' % b for b in data[i:i+24])+',' for i in range(0,len(data),24))
        result.append('};')
        length = 'sizeof('+name+')'
        mime = 'application/wasm'
    else:
        result.append(f'static const char {name}[] =')
        # Bound C literal size even for generated/minified vendor JS.
        data = path.read_text(encoding='utf-8')
        result.extend(json.dumps(data[i:i+4000], ensure_ascii=True) for i in range(0,len(data),4000))
        result[-1] += ';'
        length = 'sizeof('+name+')-1'
        mime = 'text/html; charset=utf-8' if filename.endswith('.html') else 'application/javascript'
    assets.append(('/' if filename=='index.html' else '/probe' if filename=='probe.html' else '/'+filename,name,length,mime))
result.append('static bool showcase_browser_asset(const char *path, const unsigned char **data, size_t *length, const char **mime) {')
for route,name,length,mime in assets:
    result.append(f'    if (!strcmp(path,"{route}")) {{ *data=(const unsigned char *){name}; *length={length}; *mime="{mime}"; return true; }}')
result.extend(['    return false;', '}'])
(root / 'source/browser_assets.h').write_text('\n'.join(result) + '\n', encoding='utf-8')
