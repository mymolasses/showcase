#!/usr/bin/env python3
"""Embed local browser assets, so existing on-device packages need no web root."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
result = ['/* Generated by tools/embed_browser.py; SPDX-License-Identifier: GPL-3.0-or-later */', '#pragma once']
for filename, name in [('index.html', 'browser_index_html'), ('player.js', 'browser_player_js')]:
    result.append(f'static const char {name}[] =')
    result.extend(json.dumps(line + '\n', ensure_ascii=True) for line in (root / 'web' / filename).read_text().splitlines())
    result[-1] += ';'
(root / 'source/browser_assets.h').write_text('\n'.join(result) + '\n')
